def build_cases():
    w1_path = ROOT / "eval" / "testsets" / "week1_inputs.jsonl"
    w1_rows = [json.loads(line) for line in w1_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    assert len(w1_rows) == 25

    all_cases = []
    for row in w1_rows:
        extra = W1_ENRICHMENTS[row["id"]]
        merged = {
            "id": row["id"],
            "lang": row["lang"],
            "category": row["category"],
            "case_type": extra["case_type"],
            "ingredients": row["ingredients"],
            "text": row["text"],
            "expected_intent": extra["expected_intent"],
            "expected_category": extra["expected_category"],
            "expected_urgency": row["expected_urgency"],
            "expected_abstention": extra["expected_abstention"],
            "expected_injection": extra["expected_injection"],
            "pair_id": extra["pair_id"],
            "expected_entities": extra["expected_entities"],
            "expected_behavior": row["expected_behavior"],
            "forbidden_claims": extra["forbidden_claims"],
            "notes": row["notes"],
        }
        all_cases.append(merged)

    all_cases.extend(NEW_W2_CASES)
    assert len(all_cases) == 40
    return all_cases


def main():
    cases = build_cases()
    out_path = ROOT / "eval" / "testsets" / "week2_cases.jsonl"
    out_path.write_text(
        "\n".join(json.dumps(c, ensure_ascii=False) for c in cases) + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(cases)} cases to {out_path}")


if __name__ == "__main__":
    main()
